# Each case verified for:
#   - spinor norm = 1
#   - ⟨F²⟩ = F(F+1) exact
#   - Schur isotropy ⟨F_a²⟩ = F(F+1)/3 for a=x,y,z
#   - ⟨F⟩ = 0
#   - group equivariance g·ζ = χ(g)·ζ
#   - β_S^{c_0} per channel
